#ifndef TR_FX_SWING_V1_H
#define TR_FX_SWING_V1_H

/* WSF_FXSwingV1 포팅 (원본 433줄, 완전 제공). 해외선물 전용 스윙 고저·피병나치 메모리.
 * OSF_SwingFibMemoryV4의 개조판 — 리셋 교체 + 동일 봉 재평가 복원 블록 추가 (원본 101~155줄).
 *
 * 상태 기계 (세션초기화==0인 평가에서만 진행, 원본 183~360줄):
 * - 전환 감지: 양수전환 = 직전미래방향<=0 && 핵심세션미래방향>0, 음수전환은 대칭 (185~186줄).
 * - 대기(보류) 구간: 전환 신호가 오면 대기 시작. 같은 방향이 대기Count를 채우고
 *   최소전환유지봉수에 닿으면 확정 — 반대편 '지난' 구간 메모리(최고/최저/크기/382/500/618/
 *   Count)를 확정하고, 이전 메모리의 유지(382/500/618)·붕괴·확장(100/138.2/161.8/200/238.2)·
 *   구조약화를 계산한다 (200~299줄). 방향이 뒤집히면 대기를 현재 구간에 흡수(merge)한다
 *   (304~320줄). 방향 0이면 대기는 동결된다 (아무 분기도 타지 않음).
 * - 실효등급은 매 호출 끝에 계산한다 (410~422줄): -1=데이터 없음, -2=붕괴,
 *   0=얕은목표, 1=중간목표, 2=깊은목표. 구조약화는 한 단계 다운그레이드.
 *   유지 플래그의 포함관계는 레벨 정의 방향에 따라 다르다: 지난상승은 618유지가
 *   가장 엄격(되돌림 저가가 가장 높은 선 위 = 가장 얕은 되돌림), 지난하락은 382유지가
 *   가장 엄격(반등 고가가 가장 낮은 선 아래). 그래서 상승 체인은 618유지부터,
 *   하락 체인은 382유지부터 검사한다 — 둘 다 가장 엄격한 것부터 좁혀 들어가는
 *   원본 규칙(401~404줄)과 일치한다.
 *
 * 동일 봉 재평가 복원 (원본 101~155줄): 모든 상태_ 변수를 [1](직전 봉 말 값)으로 복원해
 * 진행 봉 재평가에서 카운터가 중복 누적되지 않게 한다. 포팅은 봉 말 스냅샷(prev_bar)으로
 * 재현한다: 새 봉 첫 평가에서 스냅샷을 갱신하고, 같은 봉 재평가는 스냅샷에서 시작한다.
 * (새 봉의 [1] 복원은 상태가 그대로라 무조건 항등 — 같은 의미다.)
 *
 * yl_var 미적용: 모든 상태가 스칼라 또는 [1] 깊이다 (docs/PORTING.md 전환 기준 ①) —
 * 핵심세션미래방향의 과거값도 [1] 대신 상태_직전미래방향을 쓴다 (원본 63~64줄).
 * 따라서 relink는 필요 없다 (자기참조 저장소가 없다).
 *
 * 세션초기화==1이면 전 상태를 지우고 그 평가는 상태 기계를 진행하지 않는다
 * (원본 156~182줄 — 리셋 봉은 카운팅하지 않는다). 출력 단계는 리셋 봉에도 실행된다.
 * 세션봉수 입력은 선언만 되고 본문에서 사용하지 않는다 (불명 — 입력 구조체에는 유지).
 */

#include <stdbool.h>
#include <stdint.h>

typedef struct {
    bool session_reset;     /* 세션초기화 */
    int32_t session_bars;   /* 세션봉수 (원본 본문 미사용 — 체인 계약상 전달만) */
    double future_dir;      /* 핵심세션미래방향 (수치) */
    int32_t min_hold_bars;  /* 최소전환유지봉수 */
    double high, low;       /* H/L builtin 대응 */
    bool is_new_bar;        /* 새 봉 첫 평가 (복원 스냅샷 갱신 트리거) */
} tr_fxsw_input_t;

/* 확정된 스윙 구간 한 쪽의 메모리 (지난상승/지난하락 공통 레이아웃) */
typedef struct {
    double high, low;        /* 최고가/최저가 */
    double count;            /* Count (원본 수치형 — 시간비율의 피제수) */
    double size;             /* 크기 = 최고가 − 최저가 */
    double lvl_382, lvl_500, lvl_618; /* 382/500/618 */
    int keep_382, keep_500, keep_618; /* 382/500/618유지 (0/1) */
    double ext_100, ext_1382, ext_1618, ext_200, ext_2382; /* 확장100~2382 */
    int weak;                /* 구조약화 (0/1) */
    int broken;              /* 붕괴 (0/1) */
} tr_fxsw_leg_t;

/* 봉 말 스냅샷 대상 상태 (원본 상태_* 대응. 실효등급·양수전환·음수전환은 매 평가
 * 재계산되어 스냅샷 의미가 없으므로 제외 — 원본도 출력 단계에서 덮어쓴다) */
typedef struct {
    /* 진행 구간 */
    double up_high, up_low, up_count;   /* 상태_핵심상승최고가/최저가/Count */
    double dn_high, dn_low, dn_count;   /* 상태_핵심하락최고가/최저가/Count */
    /* 확정 메모리 */
    tr_fxsw_leg_t lup, ldn;             /* 상태_핵심지난상승/하락 * */
    /* 방향·환경 */
    int leg_dir;                        /* 상태_핵심방향구간방향 (−1/0/+1) */
    double time_ratio;                  /* 상태_시간비율 */
    double prev_dir;                    /* 상태_직전미래방향 */
    /* 대기(보류) 구간 */
    int wait_dir;                       /* 상태_대기방향 */
    double wait_count;                  /* 상태_대기Count */
    double wait_high, wait_low;         /* 상태_대기최고가/최저가 */
} tr_fxsw_state_t;

typedef struct {
    tr_fxsw_state_t st;                 /* 현재 상태 */
    tr_fxsw_state_t prev_bar;           /* 직전 봉 말 스냅샷 (동일 봉 재평가 복원용) */
    bool has_bar;
    /* 출력 (원본 NumericRef 대응 — 매 평가 끝에 상태에서 복사 + 실효등급 계산) */
    tr_fxsw_leg_t out_lup, out_ldn;     /* 핵심지난상승/하락 13종 + 구조약화 */
    int out_lup_grade, out_ldn_grade;   /* 핵심지난상승/하락_실효등급 */
    int out_leg_dir;                    /* 핵심방향구간방향 */
    double out_time_ratio;              /* 시간비율 */
} tr_fxsw_t;

bool tr_fxsw_init(tr_fxsw_t *s);

/* 매 평가 호출 (새 봉·진행 봉 재평가 모두). */
void tr_fxsw_eval(tr_fxsw_t *s, const tr_fxsw_input_t *in);

#endif
